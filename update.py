#!/usr/bin/env python3
"""Regenerate Dockerfiles, versions.json, docker-compose.yml and the README
table from the upstream official images.

Ruby versions come from docker-library/ruby; Node.js LTS lines and their
Dockerfiles come from nodejs/docker-node. Every supported Ruby is paired with
every Node.js major that is currently in (active or maintenance) LTS.

Usage: python3 update.py
"""

import datetime
import json
import os
import re
import shutil
import urllib.request

RUBY_VERSIONS_URL = "https://raw.githubusercontent.com/docker-library/ruby/master/versions.json"
NODE_VERSIONS_URL = "https://raw.githubusercontent.com/nodejs/docker-node/main/versions.json"
NODE_DOCKERFILE_URL = "https://raw.githubusercontent.com/nodejs/docker-node/main/{major}/{variant}/Dockerfile"

IMAGE = "koen/ruby-node"
VARIANTS = ["bookworm", "alpine"]
DEFAULT_VARIANT = "bookworm"

ROOT = os.path.dirname(os.path.abspath(__file__))


def fetch(url):
    with urllib.request.urlopen(url, timeout=30) as response:
        return response.read().decode()


def version_key(version):
    return tuple(int(part) for part in version.split("."))


def ruby_versions(variants):
    """Supported Ruby majors (e.g. "3.4") that have every variant we build."""
    data = json.loads(fetch(RUBY_VERSIONS_URL))
    result = {}
    for major, info in data.items():
        if not info or "-" in major:  # skips EOL entries (null) and previews
            continue
        if all(any(v == variant or v.startswith(variant) for v in info["variants"]) for variant in variants):
            result[major] = info
    return dict(sorted(result.items(), key=lambda item: version_key(item[0])))


def node_lts_majors(today):
    """Node.js majors whose LTS has started and that have not reached end of life."""
    data = json.loads(fetch(NODE_VERSIONS_URL))
    result = {}
    for major, info in data.items():
        lts = info.get("lts")
        if lts and lts <= today < info["end"]:
            result[major] = info
    return dict(sorted(result.items(), key=lambda item: int(item[0])))


def node_dockerfile(major, info, variant, rubies):
    """Upstream docker-node Dockerfile, rebased on the official Ruby image."""
    upstream_variant = info["alpine-default"] if variant == "alpine" else variant
    source = fetch(NODE_DOCKERFILE_URL.format(major=major, variant=upstream_variant))

    if variant == "alpine":
        # Use the Alpine release Node.js was built for when every Ruby offers it.
        offered = all(upstream_variant in info["variants"] for info in rubies.values())
        ruby_tag = upstream_variant if offered else "alpine"
    else:
        ruby_tag = variant

    lines = source.splitlines()
    from_index = next(i for i, line in enumerate(lines) if line.startswith("FROM "))
    body = [
        line
        for line in lines[from_index + 1:]
        if not re.match(r"^(COPY docker-entrypoint\.sh|ENTRYPOINT|CMD)\b", line)
    ]
    while body and not body[-1].strip():
        body.pop()

    header = [
        "# This file is generated by update.py, do not edit it directly.",
        "",
        "ARG RUBY_VERSION",
        "",
        f"FROM ruby:${{RUBY_VERSION}}-{ruby_tag}",
        "",
        f"# Below is verbatim from https://github.com/nodejs/docker-node/blob/main/{major}/{upstream_variant}/Dockerfile",
    ]
    return "\n".join(header + body) + "\n", re.search(r"^ENV NODE_VERSION[= ](\S+)", source, re.M).group(1)


def write(path, content):
    with open(os.path.join(ROOT, path), "w") as file:
        file.write(content)


def main():
    today = datetime.date.today().isoformat()
    rubies = ruby_versions(VARIANTS)
    nodes = node_lts_majors(today)
    if not rubies or not nodes:
        raise SystemExit("No Ruby or Node.js versions found, refusing to remove everything")

    node_versions = {}
    for variant in VARIANTS:
        variant_dir = os.path.join(ROOT, variant)
        os.makedirs(variant_dir, exist_ok=True)
        for entry in os.listdir(variant_dir):
            if entry.startswith("node") and entry[4:] not in nodes:
                shutil.rmtree(os.path.join(variant_dir, entry))
        for major, info in nodes.items():
            dockerfile, node_version = node_dockerfile(major, info, variant, rubies)
            os.makedirs(os.path.join(variant_dir, f"node{major}"), exist_ok=True)
            write(f"{variant}/node{major}/Dockerfile", dockerfile)
            node_versions[major] = node_version

    newest_ruby, newest_node = list(rubies)[-1], list(nodes)[-1]
    images = []
    for ruby in rubies:
        for node in nodes:
            for variant in VARIANTS:
                tags = [f"{ruby}-{node}-{variant}"]
                if variant == DEFAULT_VARIANT:
                    tags.append(f"{ruby}-{node}")
                if ruby == newest_ruby and node == newest_node:
                    tags.append("latest" if variant == DEFAULT_VARIANT else variant)
                images.append({
                    "ruby_version": ruby,
                    "node_major": node,
                    "variant": variant,
                    "dockerfile": f"./{variant}/node{node}/Dockerfile",
                    "tags": ",".join(tags),
                })

    versions = {
        "ruby": {major: info["version"] for major, info in rubies.items()},
        "node": node_versions,
        "images": images,
    }
    write("versions.json", json.dumps(versions, indent=2) + "\n")

    compose = ["# This file is generated by update.py, do not edit it directly.", "services:"]
    for image in images:
        name = f"{image['ruby_version']}-{image['node_major']}-{image['variant']}"
        compose += [
            f"  rubynode-{name}:",
            f"    image: {IMAGE}:{name}",
            "    build:",
            f"      context: ./{image['variant']}/node{image['node_major']}",
            "      platforms:",
            "        - linux/amd64",
            "      args:",
            f"        RUBY_VERSION: \"{image['ruby_version']}\"",
            "",
        ]
    write("docker-compose.yml", "\n".join(compose).rstrip() + "\n")

    table = [
        "|   | " + " | ".join(f"Ruby {ruby}" for ruby in rubies) + " |",
        "| --- |" + " --- |" * len(rubies),
    ]
    for node in nodes:
        table.append(f"| Node {node} |" + " ✅ |" * len(rubies))
    readme = open(os.path.join(ROOT, "README.md")).read()
    readme = re.sub(
        r"(<!-- versions:start -->\n).*?(<!-- versions:end -->)",
        lambda match: match.group(1) + "\n".join(table) + "\n" + match.group(2),
        readme,
        flags=re.S,
    )
    write("README.md", readme)


if __name__ == "__main__":
    main()
